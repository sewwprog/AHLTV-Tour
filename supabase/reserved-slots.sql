-- AHLTV Tour: reserved tournament slots
-- Run this in the SQL editor for the Supabase project used by the AHLTV-Tour site.
-- Existing tournament/registration data is not removed.
create table if not exists public.tournament_reservations (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on delete cascade,
  team_name text not null check (char_length(btrim(team_name)) between 2 and 40),
  created_at timestamptz not null default now(),
  created_by uuid not null default auth.uid() references auth.users(id)
);
create unique index if not exists tournament_reservations_name_ci
on public.tournament_reservations (tournament_id, lower(btrim(team_name)));
create index if not exists tournament_reservations_tournament_idx
on public.tournament_reservations (tournament_id);

alter table public.tournament_reservations enable row level security;
revoke all on public.tournament_reservations from anon, authenticated;
grant select, insert, delete on public.tournament_reservations to authenticated;
grant usage, select on sequence public.tournament_reservations_id_seq to authenticated;
drop policy if exists "Admin read tournament reservations" on public.tournament_reservations;
create policy "Admin read tournament reservations" on public.tournament_reservations
for select to authenticated
using (exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())));
drop policy if exists "Admin insert tournament reservations" on public.tournament_reservations;
create policy "Admin insert tournament reservations" on public.tournament_reservations
for insert to authenticated
with check (created_by=(select auth.uid()) and exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())));
drop policy if exists "Admin delete tournament reservations" on public.tournament_reservations;
create policy "Admin delete tournament reservations" on public.tournament_reservations
for delete to authenticated
using (exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())));

-- Prevent duplicate reservations and oversubscribing confirmed teams plus held places.
create or replace function public.enforce_tournament_reservation()
returns trigger language plpgsql security invoker set search_path='' as $$
declare v_max integer; v_used integer;
begin
  select max_teams into v_max from public.tournaments where id=new.tournament_id for update;
  if v_max is null then
    raise exception using errcode='P0001', message='tournament_not_found';
  end if;
  if exists(select 1 from public.team_registrations r
            where r.tournament_id=new.tournament_id and r.status<>'rejected'
              and lower(btrim(r.team_name))=lower(btrim(new.team_name)))
    or exists(select 1 from public.manual_tournament_teams m
              where m.tournament_id=new.tournament_id
                and lower(btrim(m.team_name))=lower(btrim(new.team_name))) then
    raise exception using errcode='P0001', message='reservation_team_already_exists';
  end if;
  select
    (select count(*) from public.team_registrations r
      where r.tournament_id=new.tournament_id and r.status='approved')
    +(select count(*) from public.manual_tournament_teams m where m.tournament_id=new.tournament_id)
    +(select count(*) from public.tournament_reservations h
      where h.tournament_id=new.tournament_id and h.id<>coalesce(new.id,-1))
    into v_used;
  if v_used >= v_max then
    raise exception using errcode='P0001', message='tournament_team_limit_reached';
  end if;
  return new;
end; $$;
drop trigger if exists trg_enforce_tournament_reservation on public.tournament_reservations;
create trigger trg_enforce_tournament_reservation
before insert or update of tournament_id,team_name
on public.tournament_reservations
for each row execute function public.enforce_tournament_reservation();

-- A successful registration releases its matching reservation automatically.
-- Trigger runs only after the registration has been accepted by database constraints.
create or replace function public.release_tournament_reservation()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  if new.status<>'rejected' then
    delete from public.tournament_reservations h
    where h.tournament_id=new.tournament_id
      and lower(btrim(h.team_name))=lower(btrim(new.team_name));
  end if;
  return new;
end; $$;
revoke all on function public.release_tournament_reservation() from public, anon, authenticated;
drop trigger if exists trg_release_tournament_reservation on public.team_registrations;
create trigger trg_release_tournament_reservation
after insert or update of team_name,status,tournament_id
on public.team_registrations
for each row execute function public.release_tournament_reservation();

-- Include reservations in admission checks for approved/automatically added teams.
create or replace function public.enforce_tournament_team_limit()
returns trigger language plpgsql security invoker set search_path='' as $$
declare v_max_teams integer; v_total integer;
begin
  if new.status <> 'approved' then return new; end if;
  if tg_op='UPDATE' and old.status='approved' and old.tournament_id=new.tournament_id then return new; end if;
  select t.max_teams into v_max_teams from public.tournaments t where t.id=new.tournament_id for update;
  if v_max_teams is null then raise exception using errcode='P0001',message='tournament_not_found'; end if;
  select
    (select count(*) from public.team_registrations r
      where r.tournament_id=new.tournament_id and r.status='approved')
    +(select count(*) from public.manual_tournament_teams m where m.tournament_id=new.tournament_id)
    +(select count(*) from public.tournament_reservations h
       where h.tournament_id=new.tournament_id
         and lower(btrim(h.team_name))<>lower(btrim(new.team_name)))
    into v_total;
  if v_total>=v_max_teams then raise exception using errcode='P0001',message='tournament_team_limit_reached'; end if;
  if v_total+1>=v_max_teams then
    update public.tournaments set registration_open=false where id=new.tournament_id;
  end if;
  return new;
end; $$;

create or replace function public.enforce_manual_tournament_team()
returns trigger language plpgsql security invoker set search_path='' as $$
declare v_max_teams integer; v_total integer;
begin
  if exists(select 1 from public.team_registrations r
      where r.tournament_id=new.tournament_id and r.status<>'rejected'
      and lower(btrim(r.team_name))=lower(btrim(new.team_name))) then
    raise exception using errcode='P0001', message='team_name_already_registered';
  end if;
  select max_teams into v_max_teams from public.tournaments where id=new.tournament_id for update;
  if v_max_teams is null then raise exception using errcode='P0001',message='tournament_not_found'; end if;
  select
    (select count(*) from public.team_registrations r where r.tournament_id=new.tournament_id and r.status='approved')
    +(select count(*) from public.manual_tournament_teams m
       where m.tournament_id=new.tournament_id and m.id<>coalesce(new.id,-1))
    +(select count(*) from public.tournament_reservations h
       where h.tournament_id=new.tournament_id and lower(btrim(h.team_name))<>lower(btrim(new.team_name)))
    into v_total;
  if v_total>=v_max_teams then raise exception using errcode='P0001',message='tournament_team_limit_reached'; end if;
  if v_total+1>=v_max_teams then update public.tournaments set registration_open=false where id=new.tournament_id; end if;
  return new;
end; $$;

-- Manual team registration can also satisfy a hold, releasing it after insertion.
create or replace function public.release_manual_team_reservation()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  delete from public.tournament_reservations h
  where h.tournament_id=new.tournament_id
    and lower(btrim(h.team_name))=lower(btrim(new.team_name));
  return new;
end; $$;
revoke all on function public.release_manual_team_reservation() from public, anon, authenticated;
drop trigger if exists trg_release_manual_team_reservation on public.manual_tournament_teams;
create trigger trg_release_manual_team_reservation
after insert or update of team_name,tournament_id on public.manual_tournament_teams
for each row execute function public.release_manual_team_reservation();

-- Anonymous viewers see only the number of holds, never team names.
create or replace function public.get_tournament_reservation_counts()
returns table(tournament_id bigint, reserved_count bigint)
language sql stable security definer set search_path='' as $$
  select h.tournament_id,count(*)::bigint
  from public.tournament_reservations h
  join public.tournaments t on t.id=h.tournament_id
  where t.is_visible=true
  group by h.tournament_id;
$$;
revoke all on function public.get_tournament_reservation_counts() from public;
grant execute on function public.get_tournament_reservation_counts() to anon,authenticated;

-- Repeated execution: a matching reservation for an already-submitted team is no longer needed.
delete from public.tournament_reservations h
using public.team_registrations r
where h.tournament_id=r.tournament_id and r.status<>'rejected'
  and lower(btrim(h.team_name))=lower(btrim(r.team_name));
